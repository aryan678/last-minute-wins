"use client";

import { Suspense, useState } from "react";
import { useSearchParams } from "next/navigation";
import { api, ApiError } from "@/lib/api";
import { useApi } from "@/lib/useApi";
import { compactInr, dateLabel, inr } from "@/lib/format";
import { Card, DemoBanner, ErrorState, Kpi, Loading } from "@/components/ui";
import type { ReadinessPlan, ReadinessTask } from "@/lib/types";

const EVENTS = [
  ["SCN-001", "Demo Coastal Cyclone (SIMULATED)"],
  ["SIM-CYC-2026-01", "Cyclone Meera (SIMULATED)"],
  ["SIM-FLD-2026-02", "Riverine Flood Watch (SIMULATED)"],
];

export default function ReadinessPage() {
  return (
    <Suspense fallback={<Loading label="Loading planner…" />}>
      <Planner />
    </Suspense>
  );
}

function Planner() {
  const params = useSearchParams();
  const [eventId, setEventId] = useState(params.get("event") ?? "SIM-CYC-2026-01");
  const [plan, setPlan] = useState<ReadinessPlan | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);

  const generate = async () => {
    setLoading(true);
    setError(null);
    try { setPlan(await api.createPlan(eventId)); }
    catch (e) { setError(e instanceof ApiError ? e.message : "Could not create the plan."); }
    finally { setLoading(false); }
  };

  const updateTask = async (task: ReadinessTask, changes: { status?: string; note?: string }) => {
    try {
      const updated = await api.patchTask(task.task_id, changes);
      setPlan((p) => p && { ...p, tasks: p.tasks.map((t) => (t.task_id === updated.task_id ? updated : t)) });
    } catch (e) {
      setError(e instanceof ApiError ? e.message : "Could not update the task.");
    }
  };

  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <h1 className="text-xl font-semibold text-slate-900">Readiness planner</h1>
          <p className="text-sm text-slate-500">Operational tasks from verified exposure and visible workload assumptions.</p>
        </div>
        <div className="flex gap-2">
          <select aria-label="Event" value={eventId} onChange={(e) => setEventId(e.target.value)} className="rounded-md border border-slate-200 bg-white px-2 py-2 text-sm">
            {EVENTS.map(([id, name]) => <option key={id} value={id}>{name}</option>)}
          </select>
          <button onClick={generate} disabled={loading} className="rounded-md bg-brand-500 px-3 py-2 text-sm font-medium text-white hover:bg-brand-600 disabled:opacity-40">
            {loading ? "Generating…" : plan ? "Regenerate plan" : "Generate plan"}
          </button>
        </div>
      </div>

      <DemoBanner text="DEMO DATA. Claim volume is a planning assumption, not a forecast." />
      {error && <ErrorState message={error} />}

      {!plan && !loading && <Card><p className="text-sm text-slate-500">Choose an event and generate a plan. Nothing is saved until you generate one.</p></Card>}
      {loading && <Loading label="Building plan…" />}

      {plan && (
        <>
          <Card title="Situation" subtitle={plan.affected_region}>
            <p className="text-sm text-slate-800">{plan.situation}</p>
            <div className="mt-4 grid grid-cols-2 gap-3 lg:grid-cols-4">
              <Kpi label="Policies exposed" value={String(plan.exposure.exposed_policies)} />
              <Kpi label="Locations exposed" value={String(plan.exposure.exposed_locations)} />
              <Kpi label="Insured value" value={compactInr(plan.exposure.insured_value_inr)} hint={inr(plan.exposure.insured_value_inr)} />
              <Kpi label="Claims already reported" value={String(plan.claims_already_reported)} />
            </div>
          </Card>

          <Card title="Expected operational pressure" subtitle="Assumptions are editable in the backend configuration.">
            <div className="grid gap-4 md:grid-cols-3">
              <Kpi label="Expected claims" value={String(plan.workload.expected_claims)} hint={`Over ${plan.workload.horizon_days} days`} />
              <Kpi label="Expected claim value" value={compactInr(plan.workload.expected_claim_value_inr)} hint="Planning estimate, not payout" />
              <Kpi label="Adjuster days needed" value={plan.workload.adjuster_days_needed === null ? "—" : String(plan.workload.adjuster_days_needed)} hint={`Capacity ${plan.workload.adjuster_capacity_per_day} claims/day`} />
            </div>
            <ul className="mt-3 list-disc pl-5 text-xs text-slate-600">
              {Object.entries(plan.workload.assumptions).map(([k, v]) => <li key={k}>{k.replace(/_/g, " ")}: {String(v)}</li>)}
            </ul>
          </Card>

          <Card title="Narrative" subtitle={plan.narrative.source === "vertex_ai" ? `Generated by ${plan.narrative.model} on Vertex AI` : "DEMO FALLBACK: template text, not generated by Vertex AI"}>
            <p className="text-sm text-slate-800">{plan.narrative.text}</p>
          </Card>

          <Card title="Priority tasks" subtitle="Suggested owners and deadlines. Update status and add notes.">
            <ul className="divide-y divide-slate-100">
              {plan.tasks.map((t) => (
                <li key={t.task_id} className="grid gap-3 py-3 md:grid-cols-[1fr_auto]">
                  <div>
                    <p className="text-sm font-medium text-slate-900">{t.title}</p>
                    <p className="text-xs text-slate-600">{t.detail}</p>
                    <p className="mt-1 text-xs text-slate-500">Owner: {t.owner} · Due {dateLabel(t.due_date)} · Why: {t.reason}</p>
                    {t.notes.length > 0 && <p className="mt-1 text-xs text-slate-500">Notes: {t.notes.join(" | ")}</p>}
                  </div>
                  <div className="flex items-start gap-2">
                    <select aria-label={`Status for ${t.title}`} value={t.status} onChange={(e) => updateTask(t, { status: e.target.value })}
                      className="rounded-md border border-slate-200 px-2 py-1 text-xs">
                      {["Not started", "In progress", "Completed"].map((s) => <option key={s}>{s}</option>)}
                    </select>
                    <NoteBox onSave={(note) => updateTask(t, { note })} />
                  </div>
                </li>
              ))}
            </ul>
          </Card>

          <Card title="Limitations">
            <ul className="list-disc space-y-1 pl-5 text-sm text-slate-700">{plan.limitations.map((l) => <li key={l}>{l}</li>)}</ul>
          </Card>
        </>
      )}
    </div>
  );
}

function NoteBox({ onSave }: { onSave: (note: string) => void }) {
  const [open, setOpen] = useState(false);
  const [text, setText] = useState("");
  if (!open) return <button onClick={() => setOpen(true)} className="rounded-md border px-2 py-1 text-xs hover:bg-slate-50">Add note</button>;
  return (
    <form className="flex gap-1" onSubmit={(e) => { e.preventDefault(); if (text.trim()) { onSave(text.trim()); setText(""); setOpen(false); } }}>
      <input value={text} onChange={(e) => setText(e.target.value)} maxLength={1000} aria-label="Task note" className="w-40 rounded-md border px-2 py-1 text-xs" />
      <button className="rounded-md bg-brand-500 px-2 text-xs text-white">Save</button>
    </form>
  );
}
